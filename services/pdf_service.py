def _clean(value):

    if not value:
        return ""

    return str(value).strip()


def _normalize_question(question):
    """
    Removes numbering already generated by AI.

    Example:
        1. Evaluate...
        Q1. Evaluate...
        1) Evaluate...

    becomes:

        Evaluate...
    """

    if not question:
        return ""

    question = question.strip()

    # Remove Q1.
    question = re.sub(
        r"^\s*Q?\s*\d+\s*[\.\):\-]\s*",
        "",
        question,
        flags=re.IGNORECASE
    )

    return question.strip()


def _parse_question_paper(text):
    """Parse generated paper metadata and numbered questions safely."""
    data = {
        "college": "", "university": "", "exam": "",
        "subject": "", "topic": "", "difficulty": "",
        "exam_date": "", "exam_time": "", "marks": "",
        "semester": "", "total_questions": "", "questions": [],
    }
    if not text:
        return data

    text = str(text).replace("\r\n", "\n").replace("\r", "\n")
    lines = text.splitlines()

    patterns = {
        "college": r"^\s*COLLEGE\s*:\s*(.+)$",
        "university": r"^\s*UNIVERSITY\s*:\s*(.+)$",
        "exam": r"^\s*(?:EXAMINATION|EXAM)\s*:\s*(.+)$",
        "subject": r"^\s*Subject\s*:\s*(.+)$",
        "topic": r"^\s*Topic\s*:\s*(.+)$",
        "difficulty": r"^\s*Difficulty\s*:\s*(.+)$",
        "exam_date": r"^\s*Exam Date\s*:\s*(.+)$",
        "exam_time": r"^\s*Exam Duration\s*:\s*(.+)$",
        "marks": r"^\s*Maximum Marks\s*:\s*(.+)$",
        "total_questions": r"^\s*Total Questions\s*:\s*(.+)$",
    }

    for line in lines:
        stripped = line.strip()
        for key, pattern in patterns.items():
            m = re.match(pattern, stripped, re.I)
            if m:
                data[key] = _clean(m.group(1))
                break

    # The source format may use centered headings rather than labels.
    # Recover the first three non-empty uppercase heading lines before metadata.
    heading_candidates = []
    for line in lines:
        s = line.strip()
        if not s or set(s) <= set("=-_*# "):
            continue
        if ":" in s:
            continue
        if s.upper() == "GENERAL INSTRUCTIONS" or s.upper() == "QUESTION PAPER":
            break
        if any(c.isalpha() for c in s) and s == s.upper() and len(s) <= 140:
            heading_candidates.append(s)
    if heading_candidates:
        data["college"] = data["college"] or heading_candidates[0]
        if len(heading_candidates) > 1:
            data["university"] = data["university"] or heading_candidates[1]
        if len(heading_candidates) > 2:
            # The third centered heading is the semester (e.g. 3 SEM).
            # Keep it in the metadata box instead of printing it above the title.
            data["semester"] = data["semester"] or heading_candidates[2]

    # Some generated papers use EXAM/EXAMINATION for the semester value.
    # Move values such as "3 SEM" into Semester and do not render them as a
    # separate header line.
    if data.get("exam") and re.search(r"\b\d+\s*SEM(?:ESTER)?\b", data["exam"], re.I):
        data["semester"] = data["semester"] or data["exam"]
        data["exam"] = ""

    # Parse ONLY numbered question blocks. This prevents General Instructions
    # and metadata from becoming Q1/Q2/etc.
    marker = re.compile(r"^\s*(?:Q(?:uestion)?\s*)?(\d+)\s*[.)\-:]\s+(.+)$", re.I)
    current = None
    current_parts = []

    def flush():
        nonlocal current, current_parts
        if current is not None and current_parts:
            q = " ".join(current_parts)
            q = re.sub(r"^\s*(?:Q(?:uestion)?\s*)?\d+\s*[.)\-:]\s*", "", q, flags=re.I)
            q = re.sub(r"\s+", " ", q).strip()
            if q and len(q) >= 10:
                data["questions"].append((current, q))
        current = None
        current_parts = []

    in_questions = False
    for line in lines:
        s = line.strip()
        if not s:
            continue
        upper = re.sub(r"\s+", " ", s.upper()).strip()
        if upper == "QUESTION PAPER":
            flush()
            in_questions = True
            continue
        if upper == "END OF QUESTION PAPER":
            flush()
            break
        if upper in {"GENERAL INSTRUCTIONS", "INSTRUCTIONS"}:
            continue

        m = marker.match(s)
        if m:
            if not in_questions and data["total_questions"]:
                # Allow papers that omit the QUESTION PAPER heading.
                in_questions = True
            if in_questions:
                flush()
                current = int(m.group(1))
                current_parts = [m.group(2).strip()]
            continue

        if current is not None and in_questions:
            # Continuation of the current question.
            if not re.fullmatch(r"[-_=*#\s]+", s):
                current_parts.append(s)

    flush()

    # Remove duplicates and renumber sequentially for display.
    unique = []
    seen = set()
    for _, q in data["questions"]:
        key = re.sub(r"\s+", " ", q.lower()).strip()
        if key not in seen:
            seen.add(key)
            unique.append(q)
    data["questions"] = [(i + 1, q) for i, q in enumerate(unique)]
    return data

def _draw_box(
    pdf,
    x,
    y,
    w,
    h,
    fill=(247, 250, 253),
    border=(135, 180, 220)
):

    pdf.set_fill_color(
        *fill
    )

    pdf.set_draw_color(
        *border
    )

    pdf.set_line_width(
        0.25
    )

    pdf.rect(
        x,
        y,
        w,
        h,
        style="DF"
    )


def _draw_label_value(
    pdf,
    x,
    y,
    label,
    value,
    label_w=27,
    value_w=58
):

    pdf.set_xy(
        x,
        y
    )

    pdf.set_font(
        "NotoSans",
        "B",
        8
    )

    pdf.set_text_color(
        18,
        45,
        78
    )

    pdf.cell(
        label_w,
        5,
        label
    )

    pdf.set_font(
        "NotoSans",
        "",
        8
    )

    pdf.set_text_color(
        30,
        30,
        30
    )

    pdf.cell(
        value_w,
        5,
        value or "—"
    )


