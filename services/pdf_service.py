def create_pdf(
    question_paper,
    filename="question_paper.pdf"
):

    data = _parse_question_paper(
        question_paper
    )

    questions = data["questions"]

    pdf = QuestionPaperPDF()

    pdf.add_page()

    # ========================================================
    # EXAM / COLLEGE HEADER
    # ========================================================
    #
    # IMPORTANT:
    # College, University and Examination are placed HERE.
    # They will NOT be printed again after General Instructions.
    #

    header_y = 43

    # College
    if data["college"]:

        pdf.set_xy(
            15,
            header_y
        )

        pdf.set_font(
            "NotoSans",
            "B",
            11
        )

        pdf.set_text_color(
            18,
            57,
            105
        )

        pdf.cell(
            180,
            6,
            data["college"],
            align="C"
        )

        header_y += 6

    # University
    if data["university"]:

        pdf.set_xy(
            15,
            header_y
        )

        pdf.set_font(
            "NotoSans",
            "",
            8
        )

        pdf.set_text_color(
            70,
            70,
            70
        )

        pdf.cell(
            180,
            5,
            data["university"],
            align="C"
        )

        header_y += 5

    # Examination
    if data["exam"]:

        pdf.set_xy(
            15,
            header_y
        )

        pdf.set_font(
            "NotoSans",
            "B",
            9
        )

        pdf.set_text_color(
            18,
            57,
            105
        )

        pdf.cell(
            180,
            5,
            data["exam"],
            align="C"
        )

        header_y += 7

    # ========================================================
    # MAIN TITLE
    # ========================================================

    title_y = max(
        62,
        header_y + 2
    )

    pdf.set_fill_color(
        18,
        57,
        105
    )

    pdf.set_draw_color(
        18,
        57,
        105
    )

    pdf.rect(
        15,
        title_y,
        180,
        16,
        style="DF"
    )

    pdf.set_xy(
        18,
        title_y + 4
    )

    pdf.set_font(
        "NotoSans",
        "B",
        15
    )

    pdf.set_text_color(
        255,
        255,
        255
    )

    pdf.cell(
        174,
        8,
        "AI QUESTION PAPER GENERATOR",
        align="C"
    )

    # ========================================================
    # METADATA
    # ========================================================

    y = title_y + 22

    _draw_box(
        pdf,
        15,
        y,
        180,
        35,
        fill=(250, 252, 255)
    )

    _draw_label_value(
        pdf,
        20,
        y + 5,
        "Subject:",
        data["subject"],
        27,
        58
    )

    _draw_label_value(
        pdf,
        105,
        y + 5,
        "Sem:",
        data["semester"],
        25,
        60
    )

    _draw_label_value(
        pdf,
        20,
        y + 12,
        "Difficulty:",
        data["difficulty"],
        27,
        58
    )

    _draw_label_value(
        pdf,
        105,
        y + 12,
        "Date:",
        data["exam_date"],
        25,
        60
    )

    _draw_label_value(
        pdf,
        20,
        y + 19,
        "Questions:",
        data["total_questions"]
        or str(len(questions)),
        27,
        58
    )

    _draw_label_value(
        pdf,
        105,
        y + 19,
        "Time:",
        data["exam_time"],
        25,
        60
    )

    _draw_label_value(
        pdf,
        20,
        y + 26,
        "Max Marks:",
        data["marks"],
        27,
        58
    )

    paper_id = os.path.splitext(
        os.path.basename(filename)
    )[0].replace(
        "question_paper_",
        ""
    )

    _draw_label_value(
        pdf,
        105,
        y + 26,
        "Paper ID:",
        paper_id,
        25,
        60
    )

    # ========================================================
    # STUDENT INFORMATION
    # ========================================================

    y = y + 40

    _draw_box(
        pdf,
        15,
        y,
        180,
        27,
        fill=(246, 250, 254),
        border=(150, 195, 230)
    )

    pdf.set_xy(
        20,
        y + 4
    )

    pdf.set_font(
        "NotoSans",
        "B",
        10
    )

    pdf.set_text_color(
        18,
        57,
        105
    )

    pdf.cell(
        0,
        5,
        "Student Information"
    )

    pdf.set_font(
        "NotoSans",
        "",
        8
    )

    pdf.set_text_color(
        55,
        55,
        55
    )

    # Name
    pdf.set_xy(
        20,
        y + 12
    )

    pdf.cell(
        20,
        5,
        "Name:"
    )

    pdf.line(
        40,
        y + 17,
        102,
        y + 17
    )

    # Roll number
    pdf.set_xy(
        110,
        y + 12
    )

    pdf.cell(
        20,
        5,
        "Roll No.:"
    )

    pdf.line(
        130,
        y + 17,
        190,
        y + 17
    )

    # Course
    pdf.set_xy(
        20,
        y + 19
    )

    pdf.cell(
        25,
        5,
        "Class / Course:"
    )

    pdf.line(
        45,
        y + 24,
        102,
        y + 24
    )

    # Section
    pdf.set_xy(
        110,
        y + 19
    )

    pdf.cell(
        20,
        5,
        "Section:"
    )

    pdf.line(
        130,
        y + 24,
        190,
        y + 24
    )

    # ========================================================
    # GENERAL INSTRUCTIONS
    # ========================================================

    y = y + 32

    pdf.set_fill_color(
        18,
        57,
        105
    )

    pdf.rect(
        15,
        y,
        180,
        8,
        style="DF"
    )

    pdf.set_xy(
        19,
        y + 1.4
    )

    pdf.set_font(
        "NotoSans",
        "B",
        9
    )

    pdf.set_text_color(
        255,
        255,
        255
    )

    pdf.cell(
        170,
        5,
        "General Instructions"
    )

    instructions = [

        "All questions are compulsory.",

        "Read each question carefully before answering.",

        "Answer according to the marks allotted.",

        "Show your working wherever necessary.",

    ]

    pdf.set_font(
        "NotoSans",
        "",
        8
    )

    pdf.set_text_color(
        35,
        35,
        35
    )

    yy = y + 12

    for idx, item in enumerate(
        instructions,
        1
    ):

        pdf.set_xy(
            20,
            yy
        )

        pdf.set_font(
            "NotoSans",
            "B",
            8
        )

        pdf.cell(
            7,
            4,
            f"{idx}."
        )

        pdf.set_font(
            "NotoSans",
            "",
            8
        )

        pdf.multi_cell(
            165,
            4,
            item
        )

        yy += 5

    # ========================================================
    # QUESTIONS
    # ========================================================

    # Start questions AFTER instructions.
    questions_start_y = yy + 5

    pdf.set_y(
        questions_start_y
    )

    if questions:

        # ----------------------------------------------------
        # Remove duplicate numbering
        # ----------------------------------------------------

        cleaned_questions = []

        for original_num, question in questions:

            question = _normalize_question(
                question
            )

            if question:

                cleaned_questions.append(
                    (
                        len(cleaned_questions) + 1,
                        question
                    )
                )

        questions = cleaned_questions

        # ----------------------------------------------------
        # Sections
        # ----------------------------------------------------

        n = len(questions)

        if n >= 9:

            first_cut = max(
                1,
                n // 3
            )

            second_cut = max(
                first_cut + 1,
                (2 * n) // 3
            )

            groups = [

                questions[
                    :first_cut
                ],

                questions[
                    first_cut:second_cut
                ],

                questions[
                    second_cut:
                ]

            ]

            names = [

                "Section A",
                "Section B",
                "Section C"

            ]

            subtitles = [

                "Short Answer Questions",
                "Medium Answer Questions",
                "Long Answer Questions"

            ]

        else:

            groups = [
                questions
            ]

            names = [
                "Question Paper"
            ]

            subtitles = [
                "Answer all questions"
            ]

        # ----------------------------------------------------
        # Draw sections
        # ----------------------------------------------------

        for gi, group in enumerate(groups):

            if not group:
                continue

            # Section heading
            if pdf.get_y() > 250:

                pdf.add_page()

            pdf.set_font(
                "NotoSans",
                "B",
                13
            )

            pdf.set_text_color(
                18,
                57,
                105
            )

            pdf.cell(
                120,
                7,
                names[gi]
            )

            pdf.set_font(
                "NotoSans",
                "B",
                8
            )

            pdf.cell(
                60,
                7,
                subtitles[gi],
                align="R"
            )

            pdf.ln(
                8
            )

            # ------------------------------------------------
            # Questions
            # ------------------------------------------------

            for qnum, question in group:

                # Page safety
                if pdf.get_y() > 265:
                    pdf.add_page()

                # qnum is normalized by _parse_question_paper(), so the
                # final PDF numbering is always Q1, Q2, Q3...
                pdf.set_font(
                    "NotoSans",
                    "B",
                    8.5
                )

                pdf.set_text_color(
                    20,
                    35,
                    55
                )

                pdf.cell(
                    12,
                    5,
                    f"Q{qnum}."
                )

                # Question text
                pdf.set_font(
                    "NotoSans",
                    "",
                    8.5
                )

                pdf.set_text_color(
                    30,
                    30,
                    30
                )

                pdf.multi_cell(
                    168,
                    5.2,
                    question
                )

                pdf.ln(
                    2.5
                )

            # Separator
            if gi < len(groups) - 1:

                pdf.set_draw_color(
                    120,
                    160,
                    200
                )

                pdf.set_line_width(
                    0.25
                )

                pdf.line(
                    15,
                    pdf.get_y(),
                    195,
                    pdf.get_y()
                )

                pdf.ln(
                    6
                )

    else:

        pdf.set_font(
            "NotoSans",
            "",
            9
        )

        pdf.set_text_color(
            100,
            100,
            100
        )

        pdf.multi_cell(
            180,
            6,
            "No questions were found in the generated paper."
        )

    # ========================================================
    # CLOSING
    # ========================================================

    if pdf.get_y() > 255:

        pdf.add_page()

    pdf.ln(
        5
    )

    pdf.set_draw_color(
        18,
        57,
        105
    )

    pdf.line(
        15,
        pdf.get_y(),
        195,
        pdf.get_y()
    )

    pdf.ln(
        7
    )

    pdf.set_font(
        "NotoSans",
        "B",
        10
    )

    pdf.set_text_color(
        18,
        57,
        105
    )

    pdf.cell(
        180,
        6,
        "End of Question Paper",
        align="C"
    )

    pdf.ln(
        5
    )

    pdf.set_font(
        "NotoSans",
        "",
        8
    )

    pdf.set_text_color(
        90,
        90,
        90
    )

    pdf.cell(
        180,
        5,
        "Smarter Learning. Brighter Future.",
        align="C"
    )

    # ========================================================
    # SAVE
    # ========================================================

    filepath = os.path.abspath(
        filename
    )

    pdf.output(
        filepath
    )

    return filepath